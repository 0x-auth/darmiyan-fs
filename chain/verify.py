    print("  against its NEIGHBOUR. what verifies is the PAIR, and what it")
    print("  verifies is the RELATION, not any value.")
    print()
    print("  and the verification is partial, which is the honest part:")
    print("  forgery B passes everything. a valid chain from a different")
    print("  seed is undetectable. so the construct can verify that a")
    print("  transition is LAWFUL and cannot verify that a history is")
    print("  THIS one. Delta names the conjugacy class, never the member.")
    print()
    print("  that gap is the missing unit again, in its fourth costume:")
